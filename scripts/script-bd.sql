IF OBJECT_ID(N'dbo.TB_VALKY_USUARIOS', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_VALKY_USUARIOS (
        ID                      INT IDENTITY(1,1) NOT NULL,
        NOME                    NVARCHAR(120)     NOT NULL,
        EMAIL                   NVARCHAR(150)     NOT NULL,
        CPF                     NVARCHAR(11)      NOT NULL,
        TELEFONE                NVARCHAR(20)      NOT NULL,
        SENHA_HASH              NVARCHAR(255)     NOT NULL,
        PERFIL                  NVARCHAR(30)      NOT NULL CONSTRAINT DF_VALKY_USUARIOS_PERFIL DEFAULT N'USUARIA',
        CODIGO_BO               NVARCHAR(30)      NULL,
        PIN_DISFARCE            NVARCHAR(10)      NULL,
        POSSUI_MEDIDA_PROTETIVA INT               NOT NULL CONSTRAINT DF_VALKY_USUARIOS_MEDIDA DEFAULT 0,
        PERMISSAO_MICROFONE     INT               NOT NULL CONSTRAINT DF_VALKY_USUARIOS_MICROFONE DEFAULT 0,
        PERMISSAO_LOCALIZACAO   INT               NOT NULL CONSTRAINT DF_VALKY_USUARIOS_LOCALIZACAO DEFAULT 0,
        ATIVO                   INT               NOT NULL CONSTRAINT DF_VALKY_USUARIOS_ATIVO DEFAULT 1,
        CRIADO_EM               DATETIME2         NOT NULL CONSTRAINT DF_VALKY_USUARIOS_CRIADO_EM DEFAULT SYSUTCDATETIME(),
        ATUALIZADO_EM           DATETIME2         NOT NULL CONSTRAINT DF_VALKY_USUARIOS_ATUALIZADO_EM DEFAULT SYSUTCDATETIME(),
        CONSTRAINT PK_VALKY_USUARIOS PRIMARY KEY (ID),
        CONSTRAINT CK_VALKY_USUARIOS_PERFIL CHECK (PERFIL IN (N'USUARIA', N'CONTATO_CONFIANCA', N'POLICIA')),
        CONSTRAINT CK_VALKY_USUARIOS_FLAGS CHECK (
            POSSUI_MEDIDA_PROTETIVA IN (0, 1) AND PERMISSAO_MICROFONE IN (0, 1)
            AND PERMISSAO_LOCALIZACAO IN (0, 1) AND ATIVO IN (0, 1))
    );

    CREATE UNIQUE INDEX UK_VALKY_USUARIOS_EMAIL ON dbo.TB_VALKY_USUARIOS (EMAIL);
    CREATE UNIQUE INDEX UK_VALKY_USUARIOS_CPF ON dbo.TB_VALKY_USUARIOS (CPF);
    CREATE INDEX IX_VALKY_USUARIOS_BO ON dbo.TB_VALKY_USUARIOS (CODIGO_BO);
END;
GO

IF OBJECT_ID(N'dbo.TB_VALKY_CONTATOS_CONFIANCA', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_VALKY_CONTATOS_CONFIANCA (
        ID                INT IDENTITY(1,1) NOT NULL,
        USUARIO_ID        INT               NOT NULL,
        NOME              NVARCHAR(120)     NOT NULL,
        TELEFONE          NVARCHAR(20)      NOT NULL,
        EMAIL             NVARCHAR(150)     NULL,
        PARENTESCO        NVARCHAR(50)      NOT NULL,
        NOTIFICAR_POR_SMS INT               NOT NULL CONSTRAINT DF_VALKY_CONTATOS_SMS DEFAULT 1,
        NOTIFICAR_POR_APP INT               NOT NULL CONSTRAINT DF_VALKY_CONTATOS_APP DEFAULT 1,
        CRIADO_EM         DATETIME2         NOT NULL CONSTRAINT DF_VALKY_CONTATOS_CRIADO_EM DEFAULT SYSUTCDATETIME(),
        CONSTRAINT PK_VALKY_CONTATOS_CONFIANCA PRIMARY KEY (ID),
        CONSTRAINT FK_VALKY_CONTATOS_USUARIOS FOREIGN KEY (USUARIO_ID)
            REFERENCES dbo.TB_VALKY_USUARIOS (ID) ON DELETE CASCADE,
        CONSTRAINT CK_VALKY_CONTATOS_FLAGS CHECK (NOTIFICAR_POR_SMS IN (0, 1) AND NOTIFICAR_POR_APP IN (0, 1))
    );

    CREATE UNIQUE INDEX UK_VALKY_CONTATOS_USU_TEL ON dbo.TB_VALKY_CONTATOS_CONFIANCA (USUARIO_ID, TELEFONE);
END;
GO

IF OBJECT_ID(N'dbo.TB_VALKY_ALERTAS', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_VALKY_ALERTAS (
        ID            INT IDENTITY(1,1) NOT NULL,
        CODIGO_BO     NVARCHAR(30)      NOT NULL,
        LATITUDE      DECIMAL(9,6)      NOT NULL,
        LONGITUDE     DECIMAL(9,6)      NOT NULL,
        STATUS        NVARCHAR(20)      NOT NULL CONSTRAINT DF_VALKY_ALERTAS_STATUS DEFAULT N'ABERTO',
        CRIADO_EM     DATETIME2         NOT NULL CONSTRAINT DF_VALKY_ALERTAS_CRIADO_EM DEFAULT SYSUTCDATETIME(),
        ATUALIZADO_EM DATETIME2         NOT NULL CONSTRAINT DF_VALKY_ALERTAS_ATUALIZADO_EM DEFAULT SYSUTCDATETIME(),
        CONSTRAINT PK_VALKY_ALERTAS PRIMARY KEY (ID),
        CONSTRAINT CK_VALKY_ALERTAS_STATUS    CHECK (STATUS IN (N'ABERTO', N'VIATURA_A_CAMINHO', N'NO_LOCAL', N'ENCERRADO')),
        CONSTRAINT CK_VALKY_ALERTAS_LATITUDE  CHECK (LATITUDE  BETWEEN -90  AND 90),
        CONSTRAINT CK_VALKY_ALERTAS_LONGITUDE CHECK (LONGITUDE BETWEEN -180 AND 180)
    );
END;
GO

IF OBJECT_ID(N'dbo.TB_VALKY_ATUALIZACOES_STATUS', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_VALKY_ATUALIZACOES_STATUS (
        ID          INT IDENTITY(1,1) NOT NULL,
        ALERTA_ID   INT               NOT NULL,
        STATUS      NVARCHAR(20)      NOT NULL,
        OBSERVACAO  NVARCHAR(500)     NULL,
        RESPONSAVEL NVARCHAR(100)     NOT NULL,
        CRIADO_EM   DATETIME2         NOT NULL CONSTRAINT DF_VALKY_ATUALIZACOES_CRIADO_EM DEFAULT SYSUTCDATETIME(),
        CONSTRAINT PK_VALKY_ATUALIZACOES_STATUS PRIMARY KEY (ID),
        CONSTRAINT FK_VALKY_ATUALIZACOES_ALERTAS FOREIGN KEY (ALERTA_ID)
            REFERENCES dbo.TB_VALKY_ALERTAS (ID) ON DELETE CASCADE,
        CONSTRAINT CK_VALKY_ATUALIZACOES_STATUS CHECK (STATUS IN (N'ABERTO', N'VIATURA_A_CAMINHO', N'NO_LOCAL', N'ENCERRADO'))
    );

    CREATE INDEX IX_VALKY_ATUALIZACOES_ALERTA ON dbo.TB_VALKY_ATUALIZACOES_STATUS (ALERTA_ID);
END;
GO

