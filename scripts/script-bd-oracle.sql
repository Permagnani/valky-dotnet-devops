/* =====================================================================
   Valky - script-bd-oracle.sql
   DDL completo para Oracle Database (19c / 21c / 23ai - FIAP / OCI).
   Utiliza identificadores padrão em MAIÚSCULAS (TB_VALKY_*) sem necessidade
   de aspas duplas, evitando ORA-00904 (identificador inválido) e colisões
   com tabelas preexistentes no mesmo schema da FIAP.
   Idempotente: ignora erro ORA-00955 caso o objeto já exista.
   ===================================================================== */

-- 1. Tabela: TB_VALKY_USUARIOS
BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE TB_VALKY_USUARIOS (
            ID                      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
            NOME                    NVARCHAR2(120) NOT NULL,
            EMAIL                   NVARCHAR2(150) NOT NULL,
            CPF                     NVARCHAR2(11)  NOT NULL,
            TELEFONE                NVARCHAR2(20)  NOT NULL,
            SENHA_HASH              NVARCHAR2(255) NOT NULL,
            PERFIL                  NVARCHAR2(30)  DEFAULT N''USUARIA'' NOT NULL,
            CODIGO_BO               NVARCHAR2(30)  NULL,
            PIN_DISFARCE            NVARCHAR2(10)  NULL,
            POSSUI_MEDIDA_PROTETIVA NUMBER(10)     DEFAULT 0 NOT NULL,
            PERMISSAO_MICROFONE     NUMBER(10)     DEFAULT 0 NOT NULL,
            PERMISSAO_LOCALIZACAO   NUMBER(10)     DEFAULT 0 NOT NULL,
            ATIVO                   NUMBER(10)     DEFAULT 1 NOT NULL,
            CRIADO_EM               TIMESTAMP(7)   DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
            ATUALIZADO_EM           TIMESTAMP(7)   DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
            CONSTRAINT PK_VALKY_USUARIOS PRIMARY KEY (ID),
            CONSTRAINT UK_VALKY_USUARIOS_EMAIL UNIQUE (EMAIL),
            CONSTRAINT UK_VALKY_USUARIOS_CPF UNIQUE (CPF),
            CONSTRAINT CK_VALKY_USUARIOS_PERFIL CHECK (PERFIL IN (N''USUARIA'', N''CONTATO_CONFIANCA'', N''POLICIA''))
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE INDEX IX_VALKY_USUARIOS_BO ON TB_VALKY_USUARIOS (CODIGO_BO)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 AND SQLCODE != -1408 THEN RAISE; END IF;
END;
/

-- 2. Tabela: TB_VALKY_CONTATOS_CONFIANCA (Rede de Apoio da Usuária)
BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE TB_VALKY_CONTATOS_CONFIANCA (
            ID                NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
            USUARIO_ID        NUMBER(10)     NOT NULL,
            NOME              NVARCHAR2(120) NOT NULL,
            TELEFONE          NVARCHAR2(20)  NOT NULL,
            EMAIL             NVARCHAR2(150) NULL,
            PARENTESCO        NVARCHAR2(50)  NOT NULL,
            NOTIFICAR_POR_SMS NUMBER(10)     DEFAULT 1 NOT NULL,
            NOTIFICAR_POR_APP NUMBER(10)     DEFAULT 1 NOT NULL,
            CRIADO_EM         TIMESTAMP(7)   DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
            CONSTRAINT PK_VALKY_CONTATOS PRIMARY KEY (ID),
            CONSTRAINT UK_VALKY_CONTATOS_USU_TEL UNIQUE (USUARIO_ID, TELEFONE),
            CONSTRAINT FK_VALKY_CONTATOS_USUARIOS FOREIGN KEY (USUARIO_ID)
                REFERENCES TB_VALKY_USUARIOS (ID) ON DELETE CASCADE
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

-- 3. Tabela: TB_VALKY_ALERTAS
BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE TB_VALKY_ALERTAS (
            ID            NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
            CODIGO_BO     NVARCHAR2(30) NOT NULL,
            LATITUDE      NUMBER(9,6)   NOT NULL,
            LONGITUDE     NUMBER(9,6)   NOT NULL,
            STATUS        NVARCHAR2(20) DEFAULT N''ABERTO'' NOT NULL,
            CRIADO_EM     TIMESTAMP(7)  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
            ATUALIZADO_EM TIMESTAMP(7)  DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
            CONSTRAINT PK_VALKY_ALERTAS PRIMARY KEY (ID),
            CONSTRAINT CK_VALKY_ALERTAS_STATUS CHECK (STATUS IN (N''ABERTO'', N''VIATURA_A_CAMINHO'', N''NO_LOCAL'', N''ENCERRADO'')),
            CONSTRAINT CK_VALKY_ALERTAS_LAT CHECK (LATITUDE BETWEEN -90 AND 90),
            CONSTRAINT CK_VALKY_ALERTAS_LON CHECK (LONGITUDE BETWEEN -180 AND 180)
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

-- 4. Tabela: TB_VALKY_ATUALIZACOES_STATUS
BEGIN
    EXECUTE IMMEDIATE '
